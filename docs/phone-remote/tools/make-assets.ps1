# ---------- android-res/drawable ----------
function N([double]$v) { $v.ToString('0.###', $inv) }

function PathData([string]$svg) {
    $out = @()
    foreach ($m in [regex]::Matches($svg, '<(path|circle|rect)\s+([^>]*?)/>')) {
        $a = @{}
        foreach ($p in [regex]::Matches($m.Groups[2].Value, '([\w-]+)="([^"]*)"')) { $a[$p.Groups[1].Value] = $p.Groups[2].Value }
        switch ($m.Groups[1].Value) {
            'path' { $out += $a['d'] }
            'circle' {
                $cx = [double]$a['cx']; $cy = [double]$a['cy']; $r = [double]$a['r']
                $out += "M$(N ($cx - $r)),$(N $cy)a$(N $r),$(N $r) 0 1,0 $(N (2 * $r)),0a$(N $r),$(N $r) 0 1,0 -$(N (2 * $r)),0"
            }
            'rect' {
                $x = [double]$a['x']; $y = [double]$a['y']; $w = [double]$a['width']; $h = [double]$a['height']
                $rx = if ($a.ContainsKey('rx')) { [double]$a['rx'] } else { 0 }
                if ($rx -le 0) { $out += "M$(N $x),$(N $y)h$(N $w)v$(N $h)h-$(N $w)z" }
                else {
                    $iw = $w - 2 * $rx; $ih = $h - 2 * $rx
                    $out += "M$(N ($x + $rx)),$(N $y)h$(N $iw)a$(N $rx),$(N $rx) 0 0 1 $(N $rx),$(N $rx)v$(N $ih)" +
                        "a$(N $rx),$(N $rx) 0 0 1 -$(N $rx),$(N $rx)h-$(N $iw)a$(N $rx),$(N $rx) 0 0 1 -$(N $rx),-$(N $rx)" +
                        "v-$(N $ih)a$(N $rx),$(N $rx) 0 0 1 $(N $rx),-$(N $rx)z"
                }
            }
        }
    }
    $out
}

function Vector([string]$comment, [string[]]$paths, [bool]$fill) {
    $body = foreach ($d in $paths) {
        if ($fill) { "    <path`n        android:fillColor=`"#FFFFFFFF`"`n        android:pathData=`"$d`" />" }
        else {
            "    <path`n        android:fillColor=`"#00000000`"`n        android:pathData=`"$d`"`n        android:strokeColor=`"#FFFFFFFF`"`n" +
            "        android:strokeLineCap=`"round`"`n        android:strokeLineJoin=`"round`"`n        android:strokeWidth=`"1.8`" />"
        }
    }
    "<?xml version=`"1.0`" encoding=`"utf-8`"?>`n<!-- $comment Tint it in code (white source). -->`n" +
    "<vector xmlns:android=`"http://schemas.android.com/apk/res/android`"`n    android:width=`"24dp`"`n    android:height=`"24dp`"`n" +
    "    android:viewportWidth=`"24`"`n    android:viewportHeight=`"24`">`n" + ($body -join "`n") + "`n</vector>`n"
}

$res = Join-Path $plan 'android-res'
$drawable = Join-Path $res 'drawable'
if (Test-Path $drawable) { Get-ChildItem $drawable -Filter 'ic_*.xml' | Remove-Item -Force }
New-Item -ItemType Directory -Force $drawable | Out-Null
$utf8 = New-Object Text.UTF8Encoding $false
foreach ($k in $all.Keys) {
    $name = 'ic_aa_' + ($k -replace '[^a-z0-9]', '_')
    $xml = Vector "Agent Arcade icon `"$k`", the same drawing as the desktop app." (PathData $all[$k]) ($filled -contains $k)
    [IO.File]::WriteAllText((Join-Path $drawable "$name.xml"), $xml, $utf8)
}
$brandFile = @{ 'claude' = 'claude'; 'codex' = 'codex'; 'gemini' = 'gemini'; 'copilot' = 'copilot'; 'cursor-agent' = 'cursor' }
foreach ($k in $brands.Keys) {
    $xml = Vector "Mark of the agent started with the command `"$k`" (Simple Icons, CC0; the mark belongs to its maker)." @($brands[$k]) $true
    [IO.File]::WriteAllText((Join-Path $drawable ('ic_agent_' + $brandFile[$k] + '.xml')), $xml, $utf8)
}

# ---------- logo, font, launcher icon source ----------
Add-Type -AssemblyName System.Drawing
$concept = Join-Path $repo 'agent-arcade-icon-concept-2026-10-12.png'
$source = if (Test-Path $concept) { $concept } else { Join-Path $repo 'web\icon.png' }
$nodpi = Join-Path $res 'drawable-nodpi'
New-Item -ItemType Directory -Force $nodpi | Out-Null
$img = [Drawing.Image]::FromFile($source)
try {
    $bmp = New-Object Drawing.Bitmap 256, 256
    $g = [Drawing.Graphics]::FromImage($bmp)
    $g.InterpolationMode = 'HighQualityBicubic'; $g.SmoothingMode = 'HighQuality'; $g.PixelOffsetMode = 'HighQuality'; $g.CompositingQuality = 'HighQuality'
    $g.DrawImage($img, 0, 0, 256, 256)
    $g.Dispose()
    $bmp.Save((Join-Path $nodpi 'arcade_logo.png'), [Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
}
finally { $img.Dispose() }

$extras = Join-Path $plan 'android-extras'
New-Item -ItemType Directory -Force $extras | Out-Null
Copy-Item $source (Join-Path $extras 'launcher-icon-source.png') -Force

$font = Join-Path $res 'font'
New-Item -ItemType Directory -Force $font | Out-Null
$cascadia = @("$env:WINDIR\Fonts\CascadiaMono.ttf", "$env:LOCALAPPDATA\Microsoft\Windows\Fonts\CascadiaMono.ttf") | Where-Object { Test-Path $_ } | Select-Object -First 1
if ($cascadia) { Copy-Item $cascadia (Join-Path $font 'cascadia_mono.ttf') -Force }
else { Write-Warning 'Cascadia Mono not found. Download it from https://github.com/microsoft/cascadia-code/releases and save CascadiaMono.ttf as android-res\font\cascadia_mono.ttf' }
try {
    Invoke-WebRequest 'https://raw.githubusercontent.com/microsoft/cascadia-code/main/LICENSE' -UseBasicParsing -OutFile (Join-Path $extras 'LICENSE-CascadiaMono.txt')
}
catch {
    [IO.File]::WriteAllText((Join-Path $extras 'LICENSE-CascadiaMono.txt'),
        "Cascadia Mono is licensed under the SIL Open Font License 1.1: https://github.com/microsoft/cascadia-code/blob/main/LICENSE`n", $utf8)
}

"Icons: $($all.Count)  agent marks: $($brands.Count)  font: $([bool]$cascadia)"
"Done: $res"
