# Builds the Android resource pack and the mockup marks from the desktop app, so the phone app
# uses exactly the same icons, agent marks, logo and terminal font as Agent Arcade.
#   powershell -NoProfile -ExecutionPolicy Bypass -File docs\phone-remote\tools\make-assets.ps1
# Output: docs\phone-remote\android-res\ (copy its folders into app\src\main\res\ of the Android
# project), docs\phone-remote\android-extras\ and docs\phone-remote\mockups\marks.js.

$ErrorActionPreference = 'Stop'
$plan = Split-Path -Parent $PSScriptRoot
$repo = (Resolve-Path (Join-Path $plan '..\..')).Path
$js = Get-Content (Join-Path $repo 'web\app.js') -Raw
$inv = [Globalization.CultureInfo]::InvariantCulture

function Block([string]$name) {
    $m = [regex]::Match($js, "const $name = \{\r?\n(.*?)\r?\n\};", 'Singleline')
    if (-not $m.Success) { throw "$name not found in web\app.js" }
    $m.Groups[1].Value
}

function Entries([string]$block) {
    $map = [ordered]@{}
    foreach ($m in [regex]::Matches($block, "^\s*'?([\w-]+)'?:\s*'([^']*)',?\s*$", 'Multiline')) { $map[$m.Groups[1].Value] = $m.Groups[2].Value }
    $map
}

$icons = Entries (Block 'ICONS')
$brands = Entries (Block 'BRAND_LOGOS')
$colors = [ordered]@{}
$colorLine = [regex]::Match($js, 'const BRAND_COLORS = \{([^}]*)\}').Groups[1].Value
foreach ($m in [regex]::Matches($colorLine, "'?([\w-]+)'?:\s*'(#[0-9a-fA-F]{6})'")) { $colors[$m.Groups[1].Value] = $m.Groups[2].Value }
if ($icons.Count -lt 10 -or $brands.Count -lt 5 -or $colors.Count -lt 5) { throw 'Could not read the icons, marks or colors from web\app.js' }

